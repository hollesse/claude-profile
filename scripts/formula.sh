#!/usr/bin/env bash
# Prints the Homebrew formula for a release to stdout.
#
# The formula installs the prebuilt binary of the user's platform from the GitHub release.
# <dir> holds the archives the release workflow built, one per target:
#   claude-profile-<version>-<target>.tar.gz
#
# Usage: scripts/formula.sh <version> <dir> > Formula/claude-profile.rb

set -euo pipefail

if [ $# -ne 2 ]; then
    echo "usage: scripts/formula.sh <version> <dir>" >&2
    exit 2
fi
version="$1"
dir="$2"
repo="https://github.com/hollesse/claude-profile"

sha256_of() {
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum "$1" | cut -d' ' -f1
    else
        shasum -a 256 "$1" | cut -d' ' -f1
    fi
}

# Prints the `url` and `sha256` lines of one target.
asset() {
    local target="$1" file="claude-profile-$version-$1.tar.gz"
    if [ ! -f "$dir/$file" ]; then
        echo "formula: $dir/$file is missing" >&2
        exit 1
    fi
    printf '      url "%s/releases/download/v%s/%s"\n' "$repo" "$version" "$file"
    printf '      sha256 "%s"\n' "$(sha256_of "$dir/$file")"
}

mac_arm="$(asset aarch64-apple-darwin)"
mac_intel="$(asset x86_64-apple-darwin)"
linux_arm="$(asset aarch64-unknown-linux-musl)"
linux_intel="$(asset x86_64-unknown-linux-musl)"

cat <<EOF
# Homebrew formula. Generated by scripts/formula.sh in the release workflow
# (.github/workflows/release.yml) – do not edit it by hand.
#
#   brew tap hollesse/claude-profile https://github.com/hollesse/claude-profile
#   brew trust hollesse/claude-profile
#   brew install claude-profile
class ClaudeProfile < Formula
  desc "Separate Claude Code profiles on one machine"
  homepage "https://hollesse.github.io/claude-profile/"
  version "$version"
  license "MIT"

  on_macos do
    on_arm do
$mac_arm
    end
    on_intel do
$mac_intel
    end
  end

  on_linux do
    on_arm do
$linux_arm
    end
    on_intel do
$linux_intel
    end
  end

  def install
    bin.install "claude-profile"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/claude-profile --version")
    assert_match "No profiles yet", shell_output("#{bin}/claude-profile list")
  end
end
EOF
